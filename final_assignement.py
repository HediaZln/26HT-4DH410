import os, re, csv

DOSSIER_ENTREE = "Chapters"
DOSSIER_SORTIE = "Chapters_norm"
os.makedirs(DOSSIER_SORTIE, exist_ok=True)

# the machine following by a number (608, n° 608, no 608) → not changed
EXCLUSION_NUMERO = r"(?!\s+(?:n[°ºo]\.?\s*)?\d)"

REMPLACEMENTS = {
    r"\bmadame\s+Roubaud\b": "Séverine",
    r"\bmme\.?\s+Roubaud\b": "Séverine",
    r"\ble\s+mécanicien\b": "Jacques",
    r"\bla\s+Lison\b": "Lison",                         # uniformise "la Lison"
    r"\bla\s+machine\b" + EXCLUSION_NUMERO: "Lison",    # "la machine" → Lison
}

def modifier_fichiers():
    if not os.path.exists(DOSSIER_ENTREE):
        print(f"❌ Dossier '{DOSSIER_ENTREE}' introuvable.")
        return

    fichiers = sorted(f for f in os.listdir(DOSSIER_ENTREE)
                      if os.path.isfile(os.path.join(DOSSIER_ENTREE, f)))
    bilan = {motif: 0 for motif in REMPLACEMENTS}
    audit = []   # contextes des remplacements, pour contrôle

    for nom in fichiers:
        with open(os.path.join(DOSSIER_ENTREE, nom), encoding="utf-8") as f:
            contenu = f.read()

        for motif, nouveau in REMPLACEMENTS.items():
            # on garde les contextes AVANT remplacement pour l'audit
            for m in re.finditer(motif, contenu, flags=re.IGNORECASE):
                debut, fin = max(0, m.start() - 40), min(len(contenu), m.end() + 40)
                audit.append([nom, nouveau,
                              contenu[debut:fin].replace("\n", " ")])
            contenu, n = re.subn(motif, nouveau, contenu, flags=re.IGNORECASE)
            bilan[motif] += n

        with open(os.path.join(DOSSIER_SORTIE, nom), "w", encoding="utf-8") as f:
            f.write(contenu)

    print("Remplacements effectués :")
    for motif, n in bilan.items():
        print(f"  {n:4d}  {motif}")

    with open("audit_remplacements.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["fichier", "remplacé_par", "contexte_original"])
        w.writerows(audit)
    print(f"\nAudit écrit dans audit_remplacements.csv ({len(audit)} lignes)")

modifier_fichiers()

"""Creating a lexicon with NRC french"""

import glob
import csv
from collections import Counter
import pandas as pd

# --- Paramètres ---
FICHIER_NRC = "French-NRC-EmoLex.txt"
MOTIF_CORPUS = "Lemmes_Norm_Chapter*-la-bete-humaine-zola.txt"
SEUIL_FREQ = 3                       # fréquence minimale dans le corpus
POS_GARDEES = ["NOUN", "VERB", "ADJ", "ADV"]
STOPLIST = set()                     # à compléter avec tes rejets (ex. {"donner", "croire"})

EMOTIONS = ["anger", "anticipation", "disgust", "fear", "joy",
            "negative", "positive", "sadness", "surprise", "trust"]

# --- 1. Chargement du NRC et dédoublonnage par lemme français ---
nrc = pd.read_csv(FICHIER_NRC, sep="\t", encoding="utf-8")
nrc = nrc.rename(columns={"French Word": "lemme"})
nrc["lemme"] = nrc["lemme"].astype(str).str.strip().str.lower()
nrc = nrc.groupby("lemme")[EMOTIONS].max().reset_index()
print(f"Lemmes NRC uniques : {len(nrc)}")

# --- 2. Chargement du corpus lemmatisé (TagAnt : forme / POS / lemme) ---
frames = []
for chemin in sorted(glob.glob(MOTIF_CORPUS)):
    df = pd.read_csv(chemin, sep="\t", names=["forme", "pos", "lemme"],
                     quoting=csv.QUOTE_NONE, dtype=str,
                     keep_default_na=False, encoding="utf-8")
    df = df[df["forme"].str.strip() != ""]
    frames.append(df)

corpus = pd.concat(frames, ignore_index=True)
corpus["lemme"] = corpus["lemme"].str.lower()

# --- 3. Fréquence et POS dominante de chaque lemme (mots pleins seulement) ---
contenu = corpus[corpus["pos"].isin(POS_GARDEES)]
freq = Counter(contenu["lemme"])
pos_dominante = contenu.groupby("lemme")["pos"].agg(lambda s: s.mode().iat[0])

# --- 4. Sélection des candidats par catégorie ---
def candidats(masque, nom_categorie):
    sub = nrc[masque & nrc["lemme"].isin(freq)].copy()
    sub["freq_corpus"] = sub["lemme"].map(freq)
    sub["pos"] = sub["lemme"].map(pos_dominante)
    sub = sub[(sub["freq_corpus"] >= SEUIL_FREQ) & (~sub["lemme"].isin(STOPLIST))]
    sub["categorie"] = nom_categorie
    sub["decision"] = ""     # à remplir : garder / rejeter / a_verifier
    sub["remarque"] = ""
    return sub

affection = candidats(
    ((nrc["joy"] == 1) | (nrc["trust"] == 1)) & (nrc["positive"] == 1),
    "AFFECT")

violence = candidats(
    ((nrc["anger"] == 1) | (nrc["fear"] == 1) | (nrc["disgust"] == 1))
    & (nrc["negative"] == 1),
    "VIOL")

# --- 5. Export pour validation manuelle ---
colonnes = ["lemme", "categorie", "freq_corpus", "pos", "decision", "remarque"] + EMOTIONS
resultat = (pd.concat([affection, violence])
            .sort_values(["categorie", "freq_corpus"], ascending=[True, False]))
resultat[colonnes].to_csv("candidats_nrc.csv", index=False, encoding="utf-8")

print(resultat.groupby("categorie").size())

