"""
Verbs of the agents (Lison, Jacques, Séverine, Flore, Phasie) with spaCy, for Gephi.
Version 2: the subjects "il" / "elle" are resolved to a named character with a simple rule.

Input : Norm_Chapter<N>-....txt   (normalised plain text, NOT the TagAnt files)
        lexiques_documentation.csv (columns lemme, categorie, ...)
Output: verbes_agents.csv         one row per (agent, role, verb) occurrence, with the sentence
        verbes_par_agent.csv      counts per agent / role / verb lemma / lexicon category
        verification_pronoms.csv  60 random resolved pronouns to check BY HAND
        gephi_nodes.csv, gephi_edges.csv, gephi_edges_agents.csv

Pronoun rule (a heuristic, NOT a real coreference model):
  "il"   -> a male character, "elle" -> a female character (Lison counts as female)
  antecedent = the nearest earlier subject of the right gender in the same sentence,
  else the nearest earlier mention in the same sentence,
  else the subject (then the last mention) of that gender in the previous sentences.
"""
import glob, re
from collections import Counter, defaultdict
import pandas as pd

# ------------------------------------------------------------------ settings
TEXT_DIR = "Norm/"                          # folder with the 12 Norm_Chapter files
LEXICON_CSV = "lexiques_documentation.csv"
OUT_DIR = "./"
AGENTS = {"Lison", "Jacques", "Séverine", "Flore", "Phasie"}
# ALL named characters that can be the antecedent of il/elle (other characters must be here,
# otherwise "il" after "Roubaud" would wrongly be attributed to Jacques). Add names as needed.
MALE = {"Jacques", "Roubaud", "Pecqueux", "Cabuche", "Grandmorin", "Misard", "Moulin",
        "Dabadie", "Cauche", "Denizet", "Camy-Lamotte", "Lachesnaye"}
FEMALE = {"Séverine", "Flore", "Phasie", "Lison", "Philomène", "Victoire", "Guichon"}
PRONOUNS = {"il": "M", "elle": "F"}
IMPERSONAL = {"falloir", "pleuvoir", "neiger"}   # "il faut", "il pleut": no antecedent
MIN_WEIGHT = 2                              # Gephi: keep verbs used at least twice with an agent
SUBJ_DEPS = {"nsubj"}
PASS_SUBJ_DEPS = {"nsubj:pass"}
AGENT_COMPLEMENT = {"obl:agent"}
OBJ_DEPS = {"obj", "iobj", "obl:arg"}

# ------------------------------------------------------------------ 1. load texts
def to_paragraphs(text):
    """One string per paragraph: the texts are hard-wrapped, so join the lines of a paragraph."""
    text = text.replace("--", "— ")                           # dialogue dashes
    paragraphs = re.split(r"\n\s*\n", text)                   # blank line = new paragraph
    return [re.sub(r"\s*\n\s*", " ", p).strip() for p in paragraphs if p.strip()]

chapters = {}
for path in glob.glob(TEXT_DIR + "*Norm_Chapter*.txt"):
    chap = int(re.search(r"Chapter(\d+)", path).group(1))
    with open(path, encoding="utf-8") as f:
        chapters[chap] = to_paragraphs(f.read())
print(len(chapters), "chapters loaded")                       # must be 12

# ------------------------------------------------------------------ 2. parse with spaCy
import spacy
nlp = spacy.load("fr_core_news_md", disable=["ner"])          # parser + tagger + lemmatiser

def agents_of(tokens):
    """Named agents among these tokens, also following 'Jacques et Séverine' (conjuncts)."""
    found = []
    for t in tokens:
        for x in [t] + list(t.conjuncts):
            if x.text in AGENTS:
                found.append(x.text)
    return found

def named_people(sent):
    """Named characters of the sentence in reading order: [(token, 'M' or 'F')]."""
    people = []
    for t in sent:
        if t.text in MALE | FEMALE and not (t.i > 0 and t.doc[t.i - 1].lower_ in {"les", "des"}):
            people.append((t, "M" if t.text in MALE else "F"))   # "les Roubaud" = plural, skipped
    return people

def antecedent(pron, gender, people, memory):
    """Antecedent of an 'il'/'elle' (see the rule in the header)."""
    before = [t for t, g in people if g == gender and t.i < pron.i]
    subjects = [t for t in before if t.dep_ in SUBJ_DEPS | PASS_SUBJ_DEPS]
    if subjects:
        return subjects[-1].text
    if before:
        return before[-1].text
    return memory[gender]["subj"] or memory[gender]["last"]

def update(memory, people):
    """Remember who was the last subject / the last mention of each gender."""
    for t, g in people:
        memory[g]["last"] = t.text
        if t.dep_ in SUBJ_DEPS | PASS_SUBJ_DEPS:
            memory[g]["subj"] = t.text

events = []                                                    # one row per (agent, role, verb)
for chap in sorted(chapters):
    memory = {"M": {"subj": None, "last": None}, "F": {"subj": None, "last": None}}
    prev_sentence = ""
    for doc in nlp.pipe(chapters[chap], batch_size=50):
        for sent in doc.sents:
            people = named_people(sent)
            for v in sent:
                if v.pos_ != "VERB" or v.lemma_.lower() in IMPERSONAL:
                    continue
                kids = list(v.children)
                subj = [c for c in kids if c.dep_ in SUBJ_DEPS]
                if not subj and v.dep_ == "conj" and v.head.pos_ in {"VERB", "AUX"}:
                    subj = [c for c in v.head.children if c.dep_ in SUBJ_DEPS]   # "Il entra et regarda"
                doers = []                                     # [(agent, how it was found)]
                for s in subj:
                    for x in [s] + list(s.conjuncts):
                        if x.text in AGENTS:
                            doers.append((x.text, "nom"))
                        elif x.lower_ in PRONOUNS and x.pos_ == "PRON":
                            who = antecedent(x, PRONOUNS[x.lower_], people, memory)
                            if who in AGENTS:
                                doers.append((who, "pronom:" + x.lower_))
                doers += [(n, "nom") for n in agents_of([c for c in kids if c.dep_ in AGENT_COMPLEMENT])]
                patients = agents_of([c for c in kids if c.dep_ in OBJ_DEPS | PASS_SUBJ_DEPS])
                if not doers and not patients:
                    continue
                lemma = v.lemma_.lower()
                for a, how in doers:
                    events.append({"chapitre": chap, "agent": a, "role": "sujet", "verbe": lemma,
                                   "methode": how, "partenaire": ",".join(patients),
                                   "phrase_precedente": prev_sentence, "phrase": sent.text.strip()})
                for a in patients:
                    events.append({"chapitre": chap, "agent": a, "role": "objet", "verbe": lemma,
                                   "methode": "nom", "partenaire": ",".join(d for d, _ in doers),
                                   "phrase_precedente": prev_sentence, "phrase": sent.text.strip()})
            update(memory, people)                             # after the sentence, not before
            prev_sentence = sent.text.strip()

ev = pd.DataFrame(events)
ev.to_csv(OUT_DIR + "verbes_agents.csv", index=False)
print(len(ev), "events")
print(ev.groupby(["agent", "role"]).size().unstack(fill_value=0))
