"""
Lexicon analysis of La Bête humaine (TagAnt output, French model).

Input : 12 files  Lemmes_Norm_Chapter<N>-....txt  (3 tab-separated columns, no header:
        form / POS tag / lemma)
        + lexiques_documentation.csv (columns: lemme, categorie, niveau, ...)
Output: resultats_par_chapitre.csv, resultats_voisinage_cibles.csv
"""
import csv
import glob
import re
from collections import Counter

import pandas as pd

# ------------------------------------------------------------------ settings
CORPUS_DIR = "Lemmes_Norm/"                     # folder with the 12 TagAnt files
LEXICON_CSV = "lexiques_documentation.csv"      # lexicon table
OUT_DIR = "./"
CATEGORIES = ["affection", "desir", "corps", "possession", "violence", "machine"]
TARGETS = ["lison", "machine", "séverine", "flore", "phasie", "philomène", "louisette", "jacques"]
WINDOW = 5                                      # +/- 5 tokens around each target
DROP_POS = {"PUNCT", "SPACE"}                   # tags excluded from all counts

# ------------------------------------------------------------------ 1. load corpus
chapters = []
for path in glob.glob(CORPUS_DIR + "Lemmes_Norm_Chapter*.txt"):
    chap = int(re.search(r"Chapter(\d+)", path).group(1))
    df = pd.read_csv(
        path, sep="\t", names=["forme", "pos", "lemme"],
        quoting=csv.QUOTE_NONE,                 # quotes in the text are not CSV quotes
        dtype=str, keep_default_na=False, encoding="utf-8",
    )
    df = df[df.forme.str.strip() != ""].copy()  # drop blank lines (paragraph breaks)
    df["chap"] = chap
    chapters.append(df)

corpus = pd.concat(chapters).sort_values("chap", kind="stable").reset_index(drop=True)
corpus["l"] = corpus.lemme.str.lower()          # lemma case is mixed: lowercase before matching

# keep only real words; N = corpus size used as the denominator everywhere
words = corpus[~corpus.pos.isin(DROP_POS)].reset_index(drop=True)
lemmas = words.l.tolist()
chap_of = words.chap.tolist()
N = len(words)

# sanity check: a French-tagged corpus should show NOUN/VERB/ADP..., not NNP/NN
print(N, "words;", words.pos.value_counts().head(5).to_dict())

# ------------------------------------------------------------------ 2. lexicons
doc = pd.read_csv(LEXICON_CSV)
lex = {k: set(doc[doc.categorie == k].lemme) for k in CATEGORIES}

# ------------------------------------------------------------------ 3. rates per chapter
# rate = number of lemmas belonging to a lexicon, per 10,000 words
rows = []
for chap in range(1, 13):
    idx = [i for i in range(N) if chap_of[i] == chap]
    row = {"chapitre": chap, "tokens": len(idx)}
    for k in CATEGORIES:
        row[k] = round(10000 * sum(lemmas[i] in lex[k] for i in idx) / len(idx), 1)
    rows.append(row)

total = {"chapitre": "total", "tokens": N}
for k in CATEGORIES:
    total[k] = round(10000 * sum(l in lex[k] for l in lemmas) / N, 1)
rows.append(total)

by_chapter = pd.DataFrame(rows)
by_chapter.to_csv(OUT_DIR + "resultats_par_chapitre.csv", index=False)
print(by_chapter.to_string(index=False))

# ------------------------------------------------------------------ 4. neighbourhood of targets
# baseline = share of each lexicon in the whole corpus
baseline = {k: sum(l in lex[k] for l in lemmas) / N for k in CATEGORIES}

results, top_lemmas = [], {}
for target in TARGETS:
    positions = [i for i in range(N) if lemmas[i] == target]

    # window = set of token positions, so a token near two occurrences is counted once;
    # the target itself is excluded to avoid circularity
    window = set()
    for i in positions:
        for j in range(max(0, i - WINDOW), min(N, i + WINDOW + 1)):
            if j != i and lemmas[j] != target:
                window.add(j)
    n_window = len(window)

    row = {"cible": target, "occ_cible": len(positions), "tokens_fenetre": n_window}
    for k in CATEGORIES:
        hits = [lemmas[j] for j in window if lemmas[j] in lex[k]]
        row[k + "_n"] = len(hits)               # raw count: always report it
        # ratio = density in the window / density in the whole corpus
        # (1 = as expected, >1 = over-represented around the target)
        row[k + "_ratio"] = round((len(hits) / n_window) / baseline[k], 2) if n_window else None
        top_lemmas[(target, k)] = Counter(hits).most_common(6)
    results.append(row)

neighbourhood = pd.DataFrame(results)
neighbourhood.to_csv(OUT_DIR + "resultats_voisinage_cibles.csv", index=False)

print(neighbourhood[["cible", "occ_cible", "tokens_fenetre"] + [k + "_n" for k in CATEGORIES]].to_string(index=False))
print(neighbourhood[["cible"] + [k + "_ratio" for k in CATEGORIES]].to_string(index=False))

