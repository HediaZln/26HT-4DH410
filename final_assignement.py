"""
Verbs of the agents (Lison, Jacques, Séverine, Flore, Phasie) with spaCy, for Gephi.

Input : Norm_Chapter<N>-....txt   (normalised plain text, NOT the TagAnt files)
        lexiques_documentation.csv (columns lemme, categorie, ...)
Output: verbes_agents.csv         one row per (agent, role, verb) occurrence, with the sentence
        verbes_par_agent.csv      counts per agent / role / verb lemma / lexicon category
        gephi_nodes.csv, gephi_edges.csv           agent -> verb -> agent network
        gephi_edges_agents.csv    direct agent -> agent links (subject -> object of the same verb)
Only NAMED agents are used: pronouns (il, elle) are not resolved.
"""
import glob, re
from collections import Counter, defaultdict
import pandas as pd

# ------------------------------------------------------------------ settings
TEXT_DIR = "Norm/"                          # folder with the 12 Norm_Chapter files
LEXICON_CSV = "lexiques_documentation.csv"
OUT_DIR = "./"
AGENTS = {"Lison", "Jacques", "Séverine", "Flore", "Phasie", "Philomène", "Louisette"}
MIN_WEIGHT = 2                              # Gephi: keep verbs used at least twice with an agent
SUBJ_DEPS = {"nsubj"}                       # active subject
PASS_SUBJ_DEPS = {"nsubj:pass"}             # passive subject = the agent is the patient
AGENT_COMPLEMENT = {"obl:agent"}            # "par Jacques" = the agent is the doer
OBJ_DEPS = {"obj", "iobj", "obl:arg"}       # direct / indirect object ("répondre à Lison")

# ------------------------------------------------------------------ 1. load texts
def to_paragraphs(text):
    """One string per paragraph: the texts are hard-wrapped, so join the lines of a paragraph."""
    text = text.replace("--", "— ")                           # dialogue dashes
    paragraphs = re.split(r"\n\s*\n", text)                   # blank line = new paragraph
    return [re.sub(r"\s*\n\s*", " ", p).strip() for p in paragraphs if p.strip()]

chapters = {}
for path in glob.glob(TEXT_DIR + "*Norm_Chapter*.txt"):
    chap = int(re.search(r"Chapter(\d+)", path).group(1))
    with open(path, encoding="utf-8") as f:
        chapters[chap] = to_paragraphs(f.read())
print(len(chapters), "chapters loaded")                       # must be 12

# ------------------------------------------------------------------ 2. parse with spaCy
import spacy
nlp = spacy.load("fr_core_news_md", disable=["ner"])          # parser + tagger + lemmatiser

def agents_of(tokens):
    """Named agents among these tokens, also following 'Jacques et Séverine' (conjuncts)."""
    found = []
    for t in tokens:
        for x in [t] + list(t.conjuncts):
            if x.text in AGENTS:
                found.append(x.text)
    return found

events = []                                                    # one row per (agent, role, verb)
for chap in sorted(chapters):
    for doc in nlp.pipe(chapters[chap], batch_size=50):
        for v in doc:
            if v.pos_ != "VERB":
                continue
            kids = list(v.children)
            subj = [c for c in kids if c.dep_ in SUBJ_DEPS]
            if not subj and v.dep_ == "conj" and v.head.pos_ in {"VERB", "AUX"}:
                subj = [c for c in v.head.children if c.dep_ in SUBJ_DEPS]   # "Il entra et regarda"
            doers = agents_of(subj) + agents_of([c for c in kids if c.dep_ in AGENT_COMPLEMENT])
            patients = agents_of([c for c in kids if c.dep_ in OBJ_DEPS | PASS_SUBJ_DEPS])
            if not doers and not patients:
                continue
            lemma = v.lemma_.lower()
            for a in doers:
                events.append({"chapitre": chap, "agent": a, "role": "sujet", "verbe": lemma,
                               "partenaire": ",".join(patients), "phrase": v.sent.text.strip()})
            for a in patients:
                events.append({"chapitre": chap, "agent": a, "role": "objet", "verbe": lemma,
                               "partenaire": ",".join(doers), "phrase": v.sent.text.strip()})

ev = pd.DataFrame(events)
ev.to_csv(OUT_DIR + "verbes_agents.csv", index=False)
print(len(ev), "events")
print(ev.groupby(["agent", "role"]).size().unstack(fill_value=0))

# ------------------------------------------------------------------ 3. lexicon category of each verb
doc_lex = pd.read_csv(LEXICON_CSV)
cat_of = dict(zip(doc_lex.lemme.str.lower(), doc_lex.categorie))
ev["categorie"] = ev.verbe.map(cat_of).fillna("autre")

summary = (ev.groupby(["agent", "role", "verbe", "categorie"]).size()
             .reset_index(name="n").sort_values(["agent", "role", "n"], ascending=[True, True, False]))
summary.to_csv(OUT_DIR + "verbes_par_agent.csv", index=False)
for (agent, role), g in summary.groupby(["agent", "role"]):
    print(agent, role, g.head(8)[["verbe", "n"]].values.tolist())

# ------------------------------------------------------------------ 4. Gephi files
# agent --(subject)--> verb --(object)--> agent : "Jacques -> regarder -> Lison"
edges = ev.groupby(["agent", "role", "verbe"]).size().reset_index(name="Weight")
edges = edges[edges.Weight >= MIN_WEIGHT]
rows = []
for r in edges.itertuples():
    verb_id = "v:" + r.verbe
    if r.role == "sujet":
        rows.append({"Source": r.agent, "Target": verb_id, "Weight": r.Weight, "Type": "Directed", "Role": "sujet"})
    else:
        rows.append({"Source": verb_id, "Target": r.agent, "Weight": r.Weight, "Type": "Directed", "Role": "objet"})
pd.DataFrame(rows).to_csv(OUT_DIR + "gephi_edges.csv", index=False)

nodes = [{"Id": a, "Label": a, "Type": "agent", "Categorie": "agent"} for a in sorted(AGENTS)]
for verb in sorted(edges.verbe.unique()):
    nodes.append({"Id": "v:" + verb, "Label": verb, "Type": "verbe", "Categorie": cat_of.get(verb, "autre")})
pd.DataFrame(nodes).to_csv(OUT_DIR + "gephi_nodes.csv", index=False)

# direct agent -> agent links (e.g. Jacques -> Séverine), weight = number of shared verbs
direct = Counter()
verbs_of = defaultdict(list)
for e in events:
    if e["role"] == "sujet" and e["partenaire"]:
        for p in e["partenaire"].split(","):
            if p != e["agent"]:
                direct[(e["agent"], p)] += 1
                verbs_of[(e["agent"], p)].append(e["verbe"])
pd.DataFrame([{"Source": s, "Target": t, "Weight": w, "Type": "Directed",
               "Label": " ".join(sorted(set(verbs_of[(s, t)])))} for (s, t), w in direct.items()]
             ).to_csv(OUT_DIR + "gephi_edges_agents.csv", index=False)
print("Gephi files written")

